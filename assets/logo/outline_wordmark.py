"""Regenerates wordmark.py by outlining the wordmark to an SVG path.

Only needed when the typeface, weight, size or tracking changes. The result is
baked into wordmark.py so gen.py needs neither a font installed nor a network.

    python3 outline_wordmark.py <font.ttf> "Space Grotesk" 600

Requires fontTools. Note that fontTools 4.25 cannot read Google's WOFF2 subsets
(it mis-sizes the transformed 'glyf' table) — feed it a TTF.
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen

SIZE, TRACKING, TEXT = 130, -0.02, "plous"

def outline(font_path, text=TEXT, size=SIZE, tracking=TRACKING):
    f    = TTFont(font_path)
    sc   = size / f["head"].unitsPerEm
    cmap, gs, hmtx = f.getBestCmap(), f.getGlyphSet(), f["hmtx"]
    pen, bounds, x = SVGPathPen(gs), BoundsPen(gs), 0.0
    for ch in text:
        g = cmap[ord(ch)]
        t = (sc, 0, 0, -sc, x, 0)
        gs[g].draw(TransformPen(pen, t))
        gs[g].draw(TransformPen(bounds, t))
        x += hmtx[g][0] * sc + tracking * size
    return pen.getCommands(), bounds.bounds

if __name__ == "__main__":
    path, family, weight = sys.argv[1], sys.argv[2], sys.argv[3]
    d, (x0, y0, x1, y1) = outline(path)
    with open("wordmark.py", "w") as fh:
        fh.write('"""The Plous wordmark, outlined to a path.\n\n'
                 'Generated by outline_wordmark.py — do not edit by hand.\n\n'
                 'Typeface: %s %s, set at %gpx with %g em tracking.\n'
                 'Licensed under the SIL Open Font License, which permits use in a logo.\n'
                 'The glyphs are outlines here, so no font is needed to render or rebuild\n'
                 'the lockup and nothing changes from machine to machine.\n"""\n\n'
                 % (family, weight, SIZE, TRACKING))
        fh.write("FAMILY  = %r\nWEIGHT  = %r\n" % (family, weight))
        fh.write("# bounding box of the outlined path, baseline at y=0\n")
        fh.write("BOUNDS  = (%.2f, %.2f, %.2f, %.2f)\n\n" % (x0, y0, x1, y1))
        fh.write("PATH = (\n")
        for i in range(0, len(d), 100):
            fh.write("    %r\n" % d[i:i+100])
        fh.write(")\n")
    print("wrote wordmark.py — %s %s, %d chars of path, bounds %s"
          % (family, weight, len(d), (round(x0,1), round(y0,1), round(x1,1), round(y1,1))))
