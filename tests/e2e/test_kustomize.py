        app.send(":new\rEditing\r\r")
        app.expect("Add Connection")
        app.send("\x1b[B\r")
        app.expect("Add Source")
        app.send("files\r\r" + str(self.source) + "\r\r")
        app.expect("Source added")
        app.send("\x1b[C\x1b[B\r")
        app.expect("6 files")
        app.send("/notes\r\r")
        app.expect("original text")
        app.expect("Editing original file bytes")
        app.send("iprefix ")
        app.send("\x1b")
        app.expect_screen("NORMAL · Unsaved changes")
        app.send(":v\r")
        app.expect("Review only. :w saves this exact draft to the local file.")
        self.assertEqual(target.read_text(), "original text\n")
        app.send(":w\r")
        app.expect("Saved to local file")
        self.assertEqual(target.read_text(), "prefix original text\n")
