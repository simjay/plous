    def test_source_branch_opens_files_and_preserves_explicit_view(self):
        app = self.save_source()
        app.send("\r")
        app.expect_screen("platform-repo / Files")
        session_path = self.state / "session.json"
        saved = app.wait_json(session_path, lambda s: s["tool"] == "files" and s["focus"] == 0)
        connection = saved["connection"]
        self.assertEqual(saved["tree_key"], connection)
        self.assertEqual(next(iter(saved["code"].values())).get("section", 0), 0)

        for view, tool in [("Files", "files"), ("Helm", "code-helm")]:
            if view == "Helm":
                app.send("\x1b[B\x1b[B\r")
                app.expect_screen("platform-repo / Helm")
                app.send("\x1b")
                app.send("\x1b[A\x1b[A")
            for opened in [False, True]:
                app.send("\r")
                saved = app.wait_json(session_path, lambda s: s["expanded"].get(connection) == opened)
                self.assertEqual(saved["tree_key"], connection)
                self.assertEqual(saved["focus"], 0)
                self.assertEqual(saved["tool"], tool)
                app.expect_screen("platform-repo / " + view)
                app.capture_screen("source-branch-" + view.lower() + ("-open" if opened else "-closed"))

        app.send(":quit\r")
        app.assert_exit()
        app.close()
        restored = self.start()
        restored.expect_screen("Current Workspace")
        restored.send("\x1b[1;3D\x1b[C")
        restored.expect_screen("Kustomize")
        restored.expect_screen("Current Workspace")
        restored.send("\r")
        restored.expect_screen("platform-repo / Files")
        saved = restored.wait_json(session_path, lambda s: s["tool"] == "files" and s["focus"] == 0)
        self.assertEqual(saved["tree_key"], connection)

