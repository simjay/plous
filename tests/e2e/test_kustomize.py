    def choose(self, app, label):
        app.send("a\x1b[H")
        def select(option):
            app.send("\x1b[H")
            previous = None
            for _ in range(24):
                rows = app.screen()["rows"]
                selected = next((row for row in rows if "› " in row), "")
                if "› " + option in selected:
                    app.send("\r")
                    return True
                if selected == previous:
                    return False
                previous = selected
                app.send("\x1b[B")
            return False

        if select(label):
            return
        for group in ["More Tools", "Comparison Options"]:
            if select(group):
                if select(label):
                    return
                app.send("\x1b")
        self.fail("Action is not reachable: " + label)

