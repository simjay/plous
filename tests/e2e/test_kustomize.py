class KustomizeTests(unittest.TestCase):
    def setUp(self):
        directory = tempfile.TemporaryDirectory(prefix="plous-kustomize-test-")
        self.addCleanup(directory.cleanup)
        self.root = Path(directory.name)
        self.source = self.root / "source"
        for name, text in {
            "payments/base/kustomization.yaml": "resources: [deployment.yaml]\n",
            "payments/base/deployment.yaml": "apiVersion: apps/v1\nkind: Deployment\nmetadata: {name: payments}\nspec:\n  replicas: 1\n  selector: {matchLabels: {app: payments}}\n  template:\n    metadata: {labels: {app: payments}}\n    spec:\n      containers: [{name: app, image: example.invalid/payments:v1}]\n",
            "payments/overlays/dev/kustomization.yaml": "resources: [../../base]\n",
            "payments/overlays/prod/kustomization.yaml": "resources: [../../base]\nreplicas: [{name: payments, count: 3}]\n",
            "storefront/base/kustomization.yaml": "resources: []\n",
        }.items():
            path = self.source / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        bin_dir = self.root / "bin"
        bin_dir.mkdir()
        self.config = self.root / "kubeconfig"
        self.config.write_text("apiVersion: v1\nkind: Config\ncurrent-context: do-not-use\n")
        self.env = {"PATH": str(bin_dir)}
        self.state = self.root / "state"

    def start(self, stderr=None):
        app = Terminal(self.state, self.config, width=180, height=42, env_overrides=self.env, stderr=stderr)
        self.addCleanup(app.close)
        app.expect("AI assistant")
        return app

    def test_restored_sources_render_without_writing_diagnostics_to_terminal(self):
        source = self.source / "payments/overlays/dev/kustomization.yaml"
        source.write_text("bases: [../../base]\ncommonLabels: {environment: dev}\npatchesStrategicMerge:\n- |\n  apiVersion: apps/v1\n  kind: Deployment\n  metadata: {name: payments}\n  spec: {replicas: 2}\n")
        original = source.read_bytes()
        app = self.open_source()
        app.send(":quit\r")
        app.assert_exit()
        app.close()
        session_path = self.state / "session.json"
        session = json.loads(session_path.read_text())
        for preference in session["code"].values():
            preference["section"] = 0
        session_path.write_text(json.dumps(session))
        with tempfile.TemporaryFile() as diagnostics:
            restored = self.start(stderr=diagnostics)
            restored.expect_screen("Current Workspace")
            restored.send("\x1b[1;3D/platform-repo\r\x1b[B\x1b[B\x1b[B\r")
            restored.expect_screen("platform-repo / Kustomize")
            self.open_group(restored, "payments")
            restored.send("/payments/overlays/dev\rr")
            restored.expect_screen("1 resource")
            self.assertNotIn("# Warning:", restored.text())
            for size in [(80, 24), (200, 60), (120, 30)]:
                restored.resize(*size)
                restored.expect_screen("Render")
                rows = restored.capture_screen(f"terminal-native-startup-{size[0]}x{size[1]}")
                self.assertEqual(len(rows), size[1])
                self.assertEqual(rows[-2].count("╯"), 3)
                self.assertNotIn("# Warning:", restored.text())
            restored.send(":quit\r")
            restored.assert_exit()
            diagnostics.seek(0)
            self.assertEqual(diagnostics.read(), b"", "native diagnostics bypassed the renderer")
        self.assertEqual(source.read_bytes(), original)

