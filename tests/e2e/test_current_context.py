    def prepare_current(self):
        text = self.original.decode().replace("kind: Config\n", "kind: Config\ncurrent-context: local-test\n")
        contexts = ""
        clusters = ""
        for number in range(44):
            contexts += f"- name: temporary-{number:02d}\n  context: {{cluster: unused-{number}, namespace: shop}}\n"
            clusters += (f"- name: unused-{number}\n  cluster: "
                         f"{{server: 'http://127.0.0.1:{self.server.server_port}/unselected/{number}'}}\n")
        text = text.replace("clusters:\n", contexts + "clusters:\n").replace("users:\n", clusters + "users:\n")
        self.config.write_text(text)
        return text

    def test_default_opens_only_current_cluster_without_workspace(self):
        before = self.prepare_current()
        app = self.start()
        app.expect_screen("Cluster Pulse")
        app.expect_screen("Current Workspace")
        app.expect_screen("local-test")
        app.wait_json(self.state / "session.json", lambda s: s.get("mode") == 0 and s.get("tool") == "kubernetes")
        self.assertFalse(any(self.state.joinpath("workspaces").iterdir()))
        self.assertFalse(any("/unselected/" in path for _, path, _ in self.requests))
        app.send("22")
        app.expect_screen("checkout-test")
        self.assertTrue(any(path == "/api/v1/namespaces/shop/pods" for _, path, _ in self.requests))
        app.send(":N *\r")
        app.expect_screen("all namespaces")
        heading = next(row for row in app.screen()["rows"] if "AI assistant" in row)
        self.assertIn("AI assistant · local-test", heading)
        self.assertNotIn("local-test ·", heading)
        app.send(":N shop\r")
        app.expect_screen("checkout-test")
        heading = next(row for row in app.screen()["rows"] if "AI assistant" in row)
        self.assertNotIn("local-test ·", heading)
        app.send(":K\rtemporary-43")
        app.expect_screen("temporary-43")
        self.assertFalse(any("/unselected/" in path for _, path, _ in self.requests))
        app.send("\x1b")
        app.send("\x03")
        app.assert_exit()
        self.assertEqual(self.config.read_text(), before)

    def test_large_api_catalog_is_shared_and_reused_until_refresh(self):
        before = self.prepare_current()
        self.extra_api_groups = [f"fixture-{i}.example.io" for i in range(80)]
        app = self.start()
        app.wait(lambda: "Cluster Pulse" in "\n".join(app.screen()["rows"]), "large API catalog startup", timeout=5)
        app.send("22")
        app.expect_screen("checkout-test")
        self.assertEqual(sum(path == "/apis" for _, path, _ in self.requests), 1)
        self.assertEqual(sum(path.startswith("/apis/fixture-") for _, path, _ in self.requests), 80)
        app.send("11")
        app.send("22")
        app.expect_screen("checkout-test")
        self.assertEqual(sum(path == "/apis" for _, path, _ in self.requests), 1)
        app.send(":g\r")
        app.wait(lambda: sum(path == "/apis" for _, path, _ in self.requests) == 2, "explicit API rediscovery")
        app.wait(lambda: sum(path.startswith("/apis/fixture-") for _, path, _ in self.requests) == 160, "refreshed API catalog")
        app.expect_screen("checkout-test")
        app.send("\x03")
        app.assert_exit()
        self.assertEqual(self.config.read_text(), before)

    def test_hiding_double_chat_restores_overview_and_tree(self):
        before = self.prepare_current()
        app = self.start()
        app.expect_screen("Cluster Pulse")
        app.send("ccRetained draft")
        app.send("\x1b")
        for width, height in ((120, 30), (200, 60), (220, 60)):
            with self.subTest(size=(width, height)):
                app.resize(width, height)
                app.send("ii")
                app.expect_screen("double width")
                app.expect_screen("Retained draft")
                app.expect_screen("Cluster Pulse")
                app.send("ii")
                app.expect_screen("AI panel hidden")
                app.expect_screen("Cluster Pulse")
                app.expect_screen("Current Workspace")
                rows = app.capture_screen(f"chat-double-hidden-{width}x{height}")
                self.assertEqual(len(rows), height)
                self.assertTrue(rows[0].lstrip().startswith("plous"))
                self.assertEqual(rows[-2].count("╯"), 2)
                self.assertIn("AI panel hidden", rows[-1])
                self.assertNotIn("Retained draft", "\n".join(rows))
                app.send("ii")
                app.expect_screen("AI panel: normal")
                app.send("\x1b[1;3C")
                app.expect_screen("Retained draft")
        app.send("\x03")
        app.assert_exit()
        self.assertEqual(self.config.read_text(), before)
        self.assertFalse(self.mutations)

