    def test_current_draft_survives_restart(self):
        self.prepare_current()
        app = self.start()
        app.expect_screen("Cluster Pulse")
        app.send("22")
        app.expect_screen("checkout-test")
        app.send("ccRemember this temporary cluster")
        app.send("\x03")
        app.assert_exit()
        restarted = Terminal(self.state, self.config, width=160, height=40)
        self.addCleanup(restarted.close)
        restarted.expect_screen("Cluster Pulse")
        restarted.expect_screen("Remember this temporary")
        restarted.expect_screen("cluster")
        restarted.wait_json(self.state / "session.json", lambda s: s.get("mode") == 0 and s.get("tool") == "kubernetes"
                            and "Remember this temporary cluster" in s.get("drafts", {}).values())
        self.assertFalse(any(self.state.joinpath("workspaces").iterdir()))
        restarted.send("\x03")
        restarted.assert_exit()

    def test_save_as_workspace_keeps_original_draft_and_history_scope(self):
        before = self.prepare_current()
        app = self.start()
        app.expect_screen("Cluster Pulse")
        app.send("ccCurrent target draft")
        app.send("\x1b[1;3D")
        app.wait_json(self.state / "session.json", lambda s: s.get("focus") == 1)
        app.send(":s\r" + "\x1b[B" * 4)
        app.expect_screen("› Save as Workspace")
        app.send("\r")
        app.expect_screen("Workspace Name")
        app.send("\x15Saved cluster\r\r")
        app.expect_screen("Workspace saved")
        saved = app.wait_json(self.state / "session.json", lambda s: s.get("workspace") and not s["workspace"].startswith("ctx-"))
        revisions = list(self.state.glob("workspaces/*/revisions/*/change.json"))
        self.assertEqual(len(revisions), 1)
        workspace = json.loads(revisions[0].read_text())["after"]
        origin = workspace["origin_scope"]
        self.assertTrue(origin.startswith("ctx-"))
        self.assertEqual(saved["drafts"][origin], "Current target draft")
        self.assertNotIn("Current target draft", "\n".join(app.screen()["rows"]))
        self.assertEqual(workspace["connections"][0]["settings"]["context"], "local-test")
        app.send(":H\r\r/Current Workspace\r")
        app.expect_screen("Current target draft")
        app.expect_screen("History")
        app.send("\x03")
        app.assert_exit()
        self.assertEqual(self.config.read_text(), before)

