"""Shared read-only views against temporary storage and a local API fixture."""

import json
import base64

from test_explore import ExploreFixture


class ReadOnlyViewTests(ExploreFixture):
    def test_value_editor_search_expand_hide_and_persistence(self):
        value = "fixture-private-value"
        self.secret = {
            "apiVersion": "v1", "kind": "Secret", "type": "Opaque",
            "metadata": {"name": "checkout-secret", "namespace": "shop", "uid": "secret-id", "resourceVersion": "1"},
            "data": {"config.yaml": base64.b64encode(("password: " + value + "\n").encode()).decode()},
        }
        app = self.open_resource("secrets")
        app.send("\r")
        app.expect("[d Describe]")
        app.send(":copyvalue\r")
        app.expect("Choose a value")
        self.assertNotIn(value, app.text())
        start = len(app.output)
        app.send("\r")
        app.expect("Plous Editor", start)
        app.expect("Read only", start)
        app.expect(value, start)
        app.send(":f\r")
        app.expect("[:f] Restore")
        app.send("/\x1b[200~:q bb\x1b[201~")
        app.expect(":q bb")
        self.assertIsNone(app.process.poll())
        app.send("\x1b")
        start = len(app.output)
        app.send("\x1b")
        app.expect("Workspaces", start)
        start = len(app.output)
        app.send("\x1b")
        app.expect("Choose a value", start)
        start = len(app.output)
        app.send("\r")
        app.expect("Read only", start)
        app.send("\x1b[1;3C:c\r")
        app.expect("AI assistant")
        app.send("\x03")
        app.assert_exit()
        self.assertEqual(self.mutations, [])
        self.assertEqual(self.config.read_bytes(), self.original)
        for path in self.state.rglob("*.json"):
            self.assertNotIn(value, path.read_text())
            self.assertNotIn(":q bb", path.read_text())

    def test_activity_comparison_returns_to_summary_without_writing(self):
        app = self.start()
        app.send(":new\rComparison workspace\r\r")
        app.expect("Add Connection")
        app.send("\x1b")
        app.send(":3\r")
        app.expect("Workspace created")
        app.send("\r")
        app.expect("View changes")
        revisions = {p: p.read_bytes() for p in self.state.glob("workspaces/*/revisions/*/change.json")}
        self.assertEqual(len(revisions), 1)
        start = len(app.output)
        app.send("d")
        app.expect("Plous Diff Reviewer", start)
        app.expect("Empty workspace", start)
        self.assertNotIn("Save to Kubernetes", app.text(start))
        self.assertNotIn("Confirm", app.text(start))
        app.send("/\x1b[200~ii33:q\x1b[201~")
        app.expect("ii33:q")
        self.assertIsNone(app.process.poll())
        app.send("\x1b")
        start = len(app.output)
        app.send("\x1b")
        app.expect("View changes", start)
        app.expect("Workspace created", start)
        app.send(":review\r")
        start = len(app.output)
        app.send("\x1b")
        app.send("\x1b")
        app.expect("Enter", start)
        app.send("\x03")
        app.assert_exit()
        self.assertEqual({p: p.read_bytes() for p in self.state.glob("workspaces/*/revisions/*/change.json")}, revisions)
        self.assertEqual(self.mutations, [])
        self.assertEqual(self.config.read_bytes(), self.original)

    def test_yaml_reading_search_and_selection_require_explicit_edit(self):
        app = self.open_resource()
        app.send("y")
        app.expect("Read only")
        app.expect("apiVersion")
        app.send("/\x1b[200~ii33:q\x1b[201~")
        app.expect("ii33:q")
        self.assertIsNone(app.process.poll())
        start = len(app.output)
        app.send("\x1b")
        app.expect("E Edit", start)
        app.send("z\x1b[By")
        app.expect("terminal clipboard")
        app.send("\x1b[200~kind: Secret\x1b[201~")
        self.assertEqual(self.mutations, [])
        start = len(app.output)
        app.send("E")
        app.expect("NORMAL", start)
        app.send("\x03")
        app.assert_exit()
        self.assertEqual(self.mutations, [])
        session = json.loads((self.state / "session.json").read_text())
        self.assertNotIn("ii33:q", json.dumps(session))
        self.assertEqual(self.config.read_bytes(), self.original)

    def test_yaml_expand_restore_and_explicit_edit_keep_saved_layout(self):
        app = self.open_resource()
        app.send("y")
        app.expect("Read only")
        app.send(":f\r")
        app.expect("[:f] Restore")
        start = len(app.output)
        app.send(":L\r")
        app.expect("Off", start)
        app.send("/kind")
        app.send("\x1b")
        start = len(app.output)
        app.send("\x1b")
        app.expect("Read only", start)
        app.expect("Workspaces", start)
        app.send(":fullscreen\r")
        start = len(app.output)
        app.send(":linenumbers\r")
        app.expect("On", start)
        start = len(app.output)
        app.send("E")
        app.expect("NORMAL", start)
        app.send(":f\ri")
        app.send("\x1b[200~# local draft\n\x1b[201~")
        app.send("\x1b")
        app.send(":c\r")
        app.expect("AI assistant")
        app.send("\x03")
        app.assert_exit()
        session = json.loads((self.state / "session.json").read_text())
        self.assertFalse(session.get("left_hidden", False))
        self.assertFalse(session.get("right_hidden", False))
        self.assertNotIn("local draft", json.dumps(session))
        self.assertEqual(self.mutations, [])
        self.assertEqual(self.config.read_bytes(), self.original)

    def test_yaml_escape_returns_to_originating_section_before_list(self):
        app = self.open_resource()
        app.send("\r")
        app.expect("[d Describe]")
        app.expect("e Events")
        app.send("y")
        app.expect("Read only")
        app.expect("Esc Describe")
        start = len(app.output)
        app.send("\x1b")
        app.expect("[d Describe]", start)
        app.expect("Pod overview", start)
        app.send("e")
        app.expect("[e Events]")
        app.send(":yaml\r")
        app.expect("Esc Events")
        start = len(app.output)
        app.send("\x1b")
        app.expect("[e Events]", start)
        app.send("\x1b")
        start = len(app.output)
        app.send("y")
        app.expect("Read only", start)
        app.expect("Esc list", start)
        app.send("\x03")
        app.assert_exit()
        self.assertEqual(self.mutations, [])
