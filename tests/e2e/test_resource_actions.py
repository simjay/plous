    def test_pod_logs_merge_application_containers_and_switch_back(self):
        self.pod["spec"]["containers"].append({"name": "proxy", "image": "example/proxy:v1"})
        self.pod["spec"]["initContainers"] = [{"name": "setup", "image": "example/setup:v1"}]
        self.pod["status"]["containerStatuses"].append(
            {"name": "proxy", "ready": True, "restartCount": 0, "state": {"running": {}}})
        app = self.open_resource()
        self.detail(app)
        self.action(app, "logs")
        app.expect("All application containers")
        app.send("\r")
        app.expect("[checkout-test/checkout] ERROR missing database setting")
        app.expect("[checkout-test/proxy] ERROR missing database setting")
        sources = {query.get("container", [""])[0] for _, path, query in self.requests if path.endswith("/log")}
        self.assertEqual(sources, {"checkout", "proxy"})
        app.send("t")
        app.expect("2026-09-29T10:00:00Z")
        app.send("/checkout-test/proxy\r")
        app.expect("matches")
        app.send("\x1b")
        app.send("o")
        app.expect("All application containers")
        before = sum(path.endswith("/log") for _, path, _ in self.requests)
        app.send("\x1b[B\x1b[B\r")
        app.wait(lambda: sum(path.endswith("/log") for _, path, _ in self.requests) > before, "individual container logs")
        logs = [(path, query) for _, path, query in self.requests if path.endswith("/log")]
        self.assertEqual(logs[-1][1].get("container"), ["proxy"])
        app.send("o\x1b[A\x1b[A\r")
        app.wait(lambda: sum(path.endswith("/log") for _, path, _ in self.requests) >= before + 3, "return to merged containers")
        app.send("\x1b")
        app.expect("[d Describe]")
        self.assertFalse(self.mutations)
        self.finish(app)

