    def detail(self, app):
        app.send("\r")
        app.expect("[d Describe]")

    def action(self, app, command):
        count = sum(path.endswith("/selfsubjectaccessreviews") for _, path, _ in self.requests)
        app.send(":" + command + "\r")
        app.wait(lambda: sum(path.endswith("/selfsubjectaccessreviews") for _, path, _ in self.requests) > count,
                 "resource action permission checks")

    def finish(self, app):
        app.send("\x03")
        app.assert_exit()
        self.assertEqual(self.config.read_bytes(), self.original)

