    def test_scale_and_restart_require_confirmation_and_capture_exact_target(self):
        app = self.open_resource("deployments")
        self.detail(app)
        self.action(app, "scale")
        app.expect("Current desired: 1")
        app.send("\x153\r")
        app.expect("Confirm scale")
        self.assertFalse(self.mutations)
        app.send("\x1b")
        app.expect("Proposed:")
        self.assertEqual(self.deployment["spec"]["replicas"], 1)
        app.send("\r\x1b[C\r")
        app.expect("Scale request accepted")
        app.wait(lambda: self.deployment["spec"]["replicas"] == 3, "confirmed replica update")
        method, path, query, body = self.mutations[-1]
        self.assertEqual(method, "PUT")
        self.assertTrue(path.endswith("/namespaces/shop/deployments/checkout-deployment/scale"))
        self.assertEqual(body["metadata"]["uid"], "deployment-id")
