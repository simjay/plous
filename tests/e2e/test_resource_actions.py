        app.expect("Confirm restart")
        before = len(self.mutations)
        app.send("\x1b[C\r")
        app.expect("Pod template updated")
        app.wait(lambda: len(self.mutations) > before, "confirmed rollout patch")
        method, path, _, patch = self.mutations[-1]
        self.assertEqual(method, "PATCH")
        self.assertTrue(path.endswith("/namespaces/shop/deployments/checkout-deployment"))
        self.assertIn({"op": "test", "path": "/metadata/uid", "value": "deployment-id"}, patch)
        self.assertIn({"op": "test", "path": "/metadata/resourceVersion", "value": "21"}, patch)
        self.assertIn("kubectl.kubernetes.io/restartedAt", self.deployment["spec"]["template"]["metadata"]["annotations"])
        self.finish(app)

