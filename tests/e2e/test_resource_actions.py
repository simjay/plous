    def test_large_pasted_manifest_reaches_validation_without_writing(self):
        app = self.open_resource("services")
        self.detail(app)
        self.action(app, "edit")
        app.expect("Plous Editor")
        proposed = deepcopy(self.service)
        note = "UPPER café 界 bb cc :quit\n" * 600
        proposed["metadata"]["annotations"] = {"large-note": note}
        app.send("ggVG")
        pasted = ("\x1b[200~" + json.dumps(proposed, ensure_ascii=False) + "\x1b[201~").encode("utf-8")
        # A terminal can pause between the bytes of a single Unicode character.
        split = pasted.index("é".encode("utf-8")) + 1
        app.send_bytes(pasted[:split])
        app.read(0.15)
        app.send_bytes(pasted[split:])
        app.send(":v\r")
        app.expect("[:w] Save")
        app.expect("Review only. Nothing saved.")
        updates = [entry for entry in self.mutations if entry[0] == "PUT"]
        self.assertEqual(len(updates), 1)
        self.assertEqual(updates[0][2].get("dryRun"), ["All"])
        self.assertEqual(updates[0][3]["metadata"]["annotations"]["large-note"], note)
        self.assertNotIn("annotations", self.service["metadata"])
        self.finish(app)

